// 0_basics.types, 1_comparison.types, 13_io.types

// The functions on channels are in 17_out and 18_in, whose examples use these values. Here the
// channels are told apart from each other and from every other type by comparing them: stdout and
// stderr have one type, stdin another.

// Each channel has one type: comparing it with itself
((=) stdin stdin)
((=) stdout stdout)
((=) stderr stderr)
((<>) stdin stdin)
((<>) stdout stdout)
((<>) stderr stderr)
((==) stdout stdout)
((==) stdin stdin)
((==) stderr stderr)
(compare stdout stdout)
(compare stdin stdin)
(compare stderr stderr)
(min stdout stdout)
(min stdin stdin)
(min stderr stderr)

// stdout and stderr are both out_channel
((=) stdout stderr)
((=) stderr stdout)
((<>) stdout stderr)
((==) stderr stdout)
(compare stdout stderr)
(min stdout stderr)
(max stderr stdout)
((=) (min stdout stderr) stdout)
((=) (max stderr stdout) stderr)

// stdin is another type
((=) stdout stdin)
((=) stderr stdin)
((=) stdin stdout)
((=) stdin stderr)
((<>) stdout stdin)
((==) stdin stderr)
(compare stdin stdout)
(min stdout stdin)
(max stdin stderr)
((=) (min stdout stderr) stdin)
((=) (max stdin stdin) stdout)
((=) (max stdin stdin) stderr)

// None of them is any of the basic types, in either order
((=) stdin Num)
((=) stdin Str)
((=) stdin Char)
((=) stdin Flt)
((=) stdin Unit)
((=) stdin true)
((=) stdout Num)
((=) stdout Str)
((=) stdout Char)
((=) stdout Flt)
((=) stdout Unit)
((=) stdout true)
((=) stderr Num)
((=) stderr Str)
((=) stderr Char)
((=) stderr Flt)
((=) stderr Unit)
((=) stderr true)
((=) Num stdin)
((=) Str stdout)
((=) Char stderr)
((=) Flt stdin)
((=) Unit stdout)
((=) true stderr)
(min Num stdout)
(max Str stdin)
(compare Char stderr)
((=) (min stdin stdin) Num)
((=) (max stdout stdout) Str)
((=) (min stderr stderr) true)
