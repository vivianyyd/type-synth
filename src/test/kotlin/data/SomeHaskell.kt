            // addition to list, so ghc passes this but we can't detect it as is
            "filter not (cons False [])",
            "id True",
            "dropWhile null (singleton [])",
            "inc (fromMaybe Num (Just Num))",
            "id Nothing",
            "takeWhile even []",
            "catMaybes (cons Nothing (repeat (listToMaybe [])))",
            "concatMap maybeToList (repeat Nothing)",
            "id []",
            "maybeToList Nothing",
            "inc (head (filter even (cons Num (cons Num []))))",
            "inc (length (cons False (cons True [])))",
