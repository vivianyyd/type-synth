                "break :: (a -> Bool) -> [a] -> ([a], [a])",
                "reverse :: [a] -> [a]",
                "zip :: [a] -> [b] -> [(a, b)]",
                "zipWith :: (a -> b -> c) -> [a] -> [b] -> [c]",
                "unzip :: [(a, b)] -> ([a], [b])",
                "Num :: Int",
                "True :: Bool",
                "False :: Bool",
                "[] :: [a]",
                "inc :: Int -> Int",
                "not :: Bool -> Bool",
                "id :: a -> a",
                "even :: Int -> Bool",
                "either :: (a -> c) -> (b -> c) -> Either a b -> c",
                "lefts :: [Either a b] -> [a]",
