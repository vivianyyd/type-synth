    val posexs =
        listOf(
            "filter not (cons True [])",
            "(++) (repeat False) (singleton False)",
            "all even (cons Num (cons Num []))",
            "null []",
            "iterate id Num",
            "and (cons True (cons False []))",
            "any not (cons False (cons (not False) []))",
            "map even (cons Num [])",
            "cons (head (cons Num [])) []",
            "concatMap maybeToList (repeat (Just True))",
            "cons True (replicate Num True)",
            "cons (head (cons Num (cons Num []))) []",
            "inc Num",
            "cons Num (singleton Num)",
            "id Num",
            "id cons",
            "id []",
            "tail (cons True [])",
            "(++) (repeat True) (singleton True)",
            "inc (length (cons True []))",
            "cons False (replicate Num True)",
