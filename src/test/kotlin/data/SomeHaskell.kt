            "uncons (cons Num (cons Num []))",
            "map even (cons Num (cons Num []))",
            "maybeToList (Just True)",
            "all even (cons Num (cons Num []))",
            "any not (cons True (cons (not True) []))",
            "iterate not True",
            "not True",
            "or (cons True [])",
            "not False",
            "null (cons Num [])",
            "null (cons False [])",
            "null (singleton (Just Num))",
            "or (cons False (cons True []))",
            "take Num ((++) (reverse (cons False (cons True []))) (repeat False))",
            "takeWhile even (cons Num (cons Num []))",
            "tail (cons False [])",
            "uncons (cons Num (cons Num []))",
            "uncons (repeat False)",
            "(++) (cons True []) (singleton True)",
            "all isJust (cons (Just Num) (repeat Nothing))",
            "and (singleton False)",
            "any id (cons False (cons True []))",
            "catMaybes (cons (Just Num) (cons Nothing []))",
            "cons (head (cons Num [])) (repeat Num)",
            "cons (Just Num) (singleton (Just Num))",
            "dropWhile isNothing (singleton (Just Num))",
